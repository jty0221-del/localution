/** 광역시/도 key → Region */
export function findRegionByKey(key: string): Region | undefined {
  return REGIONS.find(r => r.key === key)
}

/** 광역시/도 label → Region */
export function findRegionByLabel(label: string): Region | undefined {
  return REGIONS.find(r => r.label === label)
}

/** 주소 문자열에서 광역시/도 추출 (예: "서울시 강남구 테헤란로" → '서울') */
export function extractMetroRegion(address: string): Region | null {
  if (!address) return null
  for (const r of REGIONS) {
    if (address.includes(r.label)) return r
  }
  return null
}
